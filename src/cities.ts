export const concertCities = (storefront: string) => {
  const own = storefrontCities[storefront];
  if (own) {
    return own;
  }
  const region = regions.find(({ members }) => members.includes(storefront));
  return region
    ? region.storefronts.flatMap((member) => storefrontCities[member] ?? [])
    : globalCities;
};
